# -*- coding: utf-8 -*-
"""
ขั้นที่ 4 : ตัวตัดประโยค (Sentence Splitter)
============================================

ปัญหา
-----
คนไทยเขียนเล่าเป็นประโยคยาว ๆ รวดเดียว ไม่ได้แยกบรรทัดแบบโปรแกรมเมอร์

    มีเงิน 100 บาท แล้วซื้อกาแฟ 45 บาท แล้วแสดงเงิน
    ให้คะแนนเป็น80 ; แสดงคะแนน

หนึ่งบรรทัดจึงมีได้หลายคำสั่ง ต้อง "ตัดประโยค" ก่อนจึงจะแยกวิเคราะห์ได้

หน้าที่ของโมดูลนี้
-----------------
ตอบคำถามเดียวคือ **"ขอบเขตประโยคอยู่ตรงไหนได้บ้าง"** ซึ่งเป็นความรู้เชิงภาษา
ส่วนคำถามว่า *ควรตัดตรงไหนจริง ๆ* เป็นหน้าที่ของ parser ที่จะลองแปลดู
แล้วเลือกแบบที่ทุกท่อนกลายเป็นคำสั่งได้จริง

การแบ่งงานแบบนี้เหมือนกับที่ทำกับการตัดคำเป๊ะ ๆ
    wordseg  เสนอ "คำ"     — parser ตัดสิน
    sentence เสนอ "ประโยค" — parser ตัดสิน

อันดับของจุดตัด (น้อย = น่าจะใช่มากกว่า)
    0   ตัวคั่นประโยคชัดเจน   "แล้ว" "จากนั้น" ";"   -> ตัดแล้วทิ้งตัวคั่น
    1   คำที่ขึ้นต้นคำสั่งได้    "แสดง" "ให้" "มี" ...  -> ตัดแล้วเก็บคำไว้

ข้อสำคัญเรื่องความปลอดภัย
------------------------
โมดูลนี้ถูกใช้ **เฉพาะตอนที่ทั้งบรรทัดแปลเป็นคำสั่งเดียวไม่ได้** เท่านั้น
(ดู parser.resolve)  โปรแกรมที่เคยคอมไพล์ผ่านอยู่แล้วจึงไม่มีทางเปลี่ยนความหมาย
"""

# ตัวคั่นประโยคชัดเจน — ตัดแล้วทิ้งตัวคั่นไปเลย
SEPARATOR = "SEQ"

# คำที่ขึ้นต้นคำสั่งใหม่ได้ — เจอกลางบรรทัดแปลว่าน่าจะเป็นประโยคใหม่
# ไม่รวม ELIF/ELSE เพราะต้องผูกกับบล็อก ถ้า ที่อยู่คนละบรรทัด
# ไม่รวม FUNC เพราะฟังก์ชันต้องมีบล็อกของตัวเอง เขียนต่อท้ายบรรทัดไม่ได้
STARTER_IDS = frozenset({
    "PRINT", "LET", "HAVE", "ASK", "INC", "DEC", "REPEAT", "FOREACH",
    "WHILE", "UNTIL", "COUNT", "BREAK", "CONTINUE", "RETURN", "CALL", "IF",
})

# จุดตัดที่นำมาพิจารณาต่อหนึ่งบรรทัด — กันบรรทัดยาวผิดปกติทำให้ช้า
MAX_POINTS = 16


def cut_points(tokens):
    """คืนขอบเขตประโยคที่เป็นไปได้ เรียงตามอันดับแล้ว

    คืน list ของ (ตำแหน่งที่ตัด, จำนวนโทเคนที่ทิ้ง)
    โดย "จำนวนโทเคนที่ทิ้ง" เป็น 1 สำหรับตัวคั่นอย่าง "แล้ว" ที่ไม่ใช่คำสั่ง
    และเป็น 0 สำหรับคำที่ต้องเก็บไว้เป็นส่วนหนึ่งของประโยคถัดไป
    """
    points = []
    for i in range(1, len(tokens)):
        ids = tokens[i].ids
        if not ids:
            continue
        if SEPARATOR in ids:
            points.append((0, i, 1))
        elif ids & STARTER_IDS:
            points.append((1, i, 0))
        if len(points) >= MAX_POINTS:
            break
    points.sort()
    return [(index, drop) for _rank, index, drop in points]
