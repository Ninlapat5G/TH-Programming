def _build():
    words, phrases = {}, {}
    for canon, surfaces in _ENTRIES:
        for surface in surfaces:
            if " " in surface:
                key = tuple(surface.split())
                phrases.setdefault(key, set()).add(canon)
                # ลงทะเบียนแบบเขียนติดกันให้อัตโนมัติด้วย
                words.setdefault("".join(key), set()).add(canon)
            else:
                words.setdefault(surface, set()).add(canon)
    return words, phrases


WORD_IDS, PHRASE_IDS = _build()
